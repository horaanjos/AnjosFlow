CREATE TABLE study_goals (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 type VARCHAR(20) NOT NULL CHECK(type IN ('STUDY_MINUTES','COMPLETED_TASKS')),
 target_value INTEGER NOT NULL CHECK(target_value BETWEEN 1 AND 1000000),
 period_start DATE NOT NULL, period_end DATE NOT NULL CHECK(period_end=period_start+6),
 subject_id BIGINT REFERENCES subjects(id) ON DELETE RESTRICT,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX goals_subject_period_idx ON study_goals(subject_id,period_start);