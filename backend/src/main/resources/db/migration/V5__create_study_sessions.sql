CREATE TABLE study_sessions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE RESTRICT,
 task_id BIGINT REFERENCES tasks(id) ON DELETE RESTRICT,
 started_at TIMESTAMPTZ NOT NULL, ended_at TIMESTAMPTZ NOT NULL CHECK(ended_at > started_at),
 duration_minutes INTEGER NOT NULL CHECK(duration_minutes BETWEEN 1 AND 10080), notes VARCHAR(1000),
 client_key UUID NOT NULL UNIQUE, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX sessions_subject_period_idx ON study_sessions(subject_id,ended_at);
CREATE INDEX sessions_period_idx ON study_sessions(ended_at);
CREATE INDEX sessions_task_idx ON study_sessions(task_id);