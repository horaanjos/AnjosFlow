CREATE TABLE calendar_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(150) NOT NULL CHECK (char_length(btrim(title)) BETWEEN 2 AND 150), description VARCHAR(1000),
 subject_id BIGINT REFERENCES subjects(id) ON DELETE RESTRICT,
 start_at TIMESTAMPTZ NOT NULL, end_at TIMESTAMPTZ NOT NULL CHECK(end_at > start_at),
 type VARCHAR(10) NOT NULL CHECK(type IN ('STUDY','EXAM','PERSONAL')),
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX events_period_idx ON calendar_events(start_at,end_at);
CREATE INDEX events_subject_idx ON calendar_events(subject_id);