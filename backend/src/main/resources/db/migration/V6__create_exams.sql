CREATE TABLE exams (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(150) NOT NULL CHECK(char_length(btrim(title)) BETWEEN 2 AND 150), description VARCHAR(1000),
 subject_id BIGINT REFERENCES subjects(id) ON DELETE RESTRICT,
 scheduled_at TIMESTAMPTZ NOT NULL, location VARCHAR(200),
 status VARCHAR(20) NOT NULL CHECK(status IN ('UPCOMING','COMPLETED','CANCELLED')),
 score NUMERIC(8,2) CHECK(score >= 0), max_score NUMERIC(8,2) CHECK(max_score > 0),
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 CHECK(score IS NULL OR (max_score IS NOT NULL AND score <= max_score))
);
CREATE INDEX exams_schedule_idx ON exams(scheduled_at);
CREATE INDEX exams_subject_idx ON exams(subject_id);