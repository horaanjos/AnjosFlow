CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL CHECK (char_length(btrim(title)) BETWEEN 2 AND 150),
    description VARCHAR(1000),
    subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING','IN_PROGRESS','COMPLETED')),
    priority VARCHAR(10) NOT NULL CHECK (priority IN ('LOW','MEDIUM','HIGH')),
    due_date DATE,
    estimated_minutes INTEGER CHECK (estimated_minutes BETWEEN 1 AND 10080),
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CHECK ((status = 'COMPLETED') = (completed_at IS NOT NULL))
);
CREATE INDEX tasks_subject_status_idx ON tasks(subject_id,status);
CREATE INDEX tasks_due_date_idx ON tasks(due_date);
CREATE INDEX tasks_completed_at_idx ON tasks(completed_at);