CREATE TABLE study_availability (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 day_of_week INTEGER NOT NULL CHECK(day_of_week BETWEEN 1 AND 7),
 start_time TIME NOT NULL, end_time TIME NOT NULL CHECK(end_time > start_time),
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE accepted_plans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 client_key UUID NOT NULL UNIQUE, fingerprint VARCHAR(64) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE calendar_events ADD COLUMN plan_id BIGINT REFERENCES accepted_plans(id) ON DELETE RESTRICT;
CREATE INDEX events_plan_idx ON calendar_events(plan_id);
ALTER TABLE calendar_events ADD COLUMN task_id BIGINT REFERENCES tasks(id) ON DELETE RESTRICT;
CREATE INDEX events_task_idx ON calendar_events(task_id);
