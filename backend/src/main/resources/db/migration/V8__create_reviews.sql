CREATE TABLE reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE RESTRICT,
 title VARCHAR(150) NOT NULL CHECK(char_length(btrim(title)) BETWEEN 2 AND 150), notes VARCHAR(1000),
 last_reviewed_at TIMESTAMPTZ, next_review_at DATE NOT NULL,
 interval_days INTEGER NOT NULL CHECK(interval_days IN(1,3,7,14,30)), review_count INTEGER NOT NULL CHECK(review_count>=0),
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX reviews_next_idx ON reviews(next_review_at);
CREATE INDEX reviews_subject_idx ON reviews(subject_id);