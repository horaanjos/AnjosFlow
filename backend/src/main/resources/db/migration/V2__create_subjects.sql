CREATE TABLE subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    color VARCHAR(7) NOT NULL DEFAULT '#A3B18A',
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT subjects_name_length CHECK (char_length(btrim(name)) BETWEEN 2 AND 100),
    CONSTRAINT subjects_color_format CHECK (color ~ '^#[0-9a-fA-F]{6}$'),
    CONSTRAINT subjects_audit_order CHECK (updated_at >= created_at)
);

-- Suporta a ordenação estável por nome e identificador.
CREATE INDEX subjects_name_id_idx ON subjects (name, id);